export const locale: 'fr' | 'en' = navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en';
document.documentElement.lang = locale;

/** French typography: narrow no-break spaces before ? ! ; » and after «, a no-break one before :. */
const frenchSpacing = (text: string): string =>
  text
    .replace(/ ([?!;»])/g, '\u202f$1')
    .replace(/« /g, '«\u202f')
    .replace(/ :/g, '\u00a0:');

const messages: Record<MessageKey, string> =
  locale === 'fr'
    ? (Object.fromEntries(
        Object.entries(fr).map(([key, text]) => [key, frenchSpacing(text)]),
      ) as Record<MessageKey, string>)
    : en;
const plural = new Intl.PluralRules(locale);

/**
 * Translates a key. `{name}` placeholders are replaced by params; `singular|plural` variants are
 * picked with the `count` param.
 */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  let message: string = messages[key] ?? key;
  if (message.includes('|')) {
    const [one, other] = message.split('|') as [string, string];
    message = plural.select(Number(params.count ?? 0)) === 'one' ? one : other;
  }
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  );
}

export function errorMessage(code: ErrorCode | undefined): string {
  const key = `error.${code ?? 'internal'}` as MessageKey;
  return key in messages ? t(key) : t('error.internal');
}

export const iconLabel = (icon: CategoryIcon): string => t(`icon.${icon}`);
